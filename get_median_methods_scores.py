def parse_cell(cell: str):
    """Return float value or None for '-' entries. Strips trailing '\\'."""
    c = cell.strip()
    c = c.rstrip("\\").strip()  # remove any trailing backslashes then re-strip
    if c in {"-", "–", ""}:
        return None
    try:
        return float(c)
    except ValueError:
        # As a fallback, extract the first numeric pattern if present
        m = re.search(r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?", c)
        return float(m.group(0)) if m else None

# Collect rows (skip empty lines)
raw_lines = [ln for ln in table_str.splitlines() if ln.strip()]
# Keep only lines that look like data rows (end with backslashes) and strip the trailing '\\'
rows = []
for ln in raw_lines:
    s = ln.strip()
    # Remove a trailing '\\' (one or more) and any trailing spaces
    s = re.sub(r"(\\+)\s*$", "", s).strip()
    if not s:
        continue
    rows.append(s)

main_p, main_r, main_f1 = [], [], []
inter_p, inter_r, inter_f1 = [], [], []

