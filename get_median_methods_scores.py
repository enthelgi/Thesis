    parts = [x.strip() for x in row.split("&")]
    if len(parts) < 10:
        # Not enough columns — skip defensively
        continue

    # Parse with protection against '-', stray backslashes, etc.
    p_main = parse_cell(parts[4])
    r_main = parse_cell(parts[5])
    f1_main = parse_cell(parts[6])
    p_inter = parse_cell(parts[7])
    r_inter = parse_cell(parts[8])
    f1_inter = parse_cell(parts[9])

